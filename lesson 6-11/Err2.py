#Прочитать два целых числа и вывести их частное с одним знаком после точки.
# При делении на ноль вывести «Делить на ноль нельзя».
# Нечисловой ввод обрабатывать не требуется.
try:
    a = int(input())
    b = int(input())
    result = a / b
    print(f'{result:.1f}')
except ZeroDivisionError:
    print('Делить на ноль нельзя')
