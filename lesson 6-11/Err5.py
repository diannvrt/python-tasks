#Прочитать строку и целое число — индекс. Вывести символ строки под этим индексом. 
# Если индекса нет, вывести «Нет такого символа».
# Нечисловой ввод обрабатывать не требуется.
try:
    text = str(input())
    symbol = int(input())
    print(text[symbol])
except IndexError:
    print('Нет такого символа')