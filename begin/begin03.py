# №3 Даны стороны прямоугольника a и b. Найти его площадь S = a·b и
#периметр P = 2·(a + b).
a = float(input('Сторона прямоугольника a: '))
b = float(input('Сторона прямоугольника b: '))
s = a * b
p = 2 * (a + b)
print(f'Площадь прямоугольника S = {s}')
print(f'Периметр прямоугольника P = {p}')