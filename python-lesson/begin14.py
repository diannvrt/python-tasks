#Дана длина L окружности. Найти ее радиус R и площадь S круга, ограниченного
# этой окружностью, учитывая, что L = 2·π·R, S = π·R2. В качестве значения π
# использовать 3.14.
pi = 3.14
L = float(input('Введите длину окружности: '))
R = L / (pi * 2)
S = pi * R ** 2
print(f'Радиус окружности равен: {R}')
print(f'Площадь круга равна: {S}')
