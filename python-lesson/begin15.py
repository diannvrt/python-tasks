#Дана площадь S круга. Найти его диаметр D и длину L окружности,
#ограничивающей этот круг, учитывая, что L = 2·π·R, S = π·R2. В качестве
#значения π использовать 3.14.

pi = 3.14
S = float(input('Введите площадь круга: '))
R = (S / pi) ** 0.5
D = 2 * R
L = 2 * pi * R
print(f'Диаметр круга равен: {D}')
print(f'Длина окружности равна: {L}')