#Даны катеты прямоугольного треугольника a и b.
# Найти его гипотенузу c и периметр P: c = √(a2 + b2), P = a + b + c.

a = float(input('Введите катет a: '))
b = float(input('Введите катет b: '))
c = (a ** 2 + b ** 2) ** 0.5
P = a + b + c
print(f'Гипотенуза прямоугольного треугольника равна: {c}')
print(f'Периметр прямугольного треугольника равен: {P}')
